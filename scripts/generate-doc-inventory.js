const fs = require('node:fs');
const path = require('node:path');
const { globSync } = require('glob');

const root = process.cwd();
const output = 'docs/reference-inventory.md';
const files = globSync('docs/**/*.md', { cwd: root, nodir: true })
  .filter(file => file !== output && !file.startsWith('docs/superpowers/plans/'))
  .sort();
const groups = new Map();

for (const file of files) {
  const relative = file.slice('docs/'.length);
  const section = relative.includes('/') ? relative.split('/')[0] : 'general';
  const contents = fs.readFileSync(path.join(root, file), 'utf8');
  const title = contents.match(/^#\s+(.+)$/m)?.[1] || path.basename(file, '.md');
  if (!groups.has(section)) groups.set(section, []);
  groups.get(section).push({ file: relative, title });
}

let markdown = '# Documentation reference inventory\n\n';
markdown += 'Generated by `npm run docs:inventory`. This index lists repository-owned documentation; plans under `docs/superpowers/plans` are intentionally standalone execution records. Status and launch scope are authoritative only where a document links to the current launch feature inventory.\n\n';
for (const [section, entries] of [...groups.entries()].sort()) {
  markdown += `## ${section[0].toUpperCase()}${section.slice(1)}\n\n`;
  for (const entry of entries) markdown += `- [${entry.title}](${entry.file})\n`;
  markdown += '\n';
}
fs.writeFileSync(path.join(root, output), `${markdown.trimEnd()}\n`);
console.log(`Indexed ${files.length} documentation files in ${output}`);
