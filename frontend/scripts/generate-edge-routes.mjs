import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import ts from 'typescript';

const frontendRoot = path.resolve(import.meta.dirname, '..');
const manifestPath = path.join(frontendRoot, 'edge-route-manifest.json');
const routeSources = [
    path.join(frontendRoot, 'src', 'App.tsx'),
    path.join(frontendRoot, 'src', 'routes', 'v1', 'AccountRoutes.tsx'),
    path.join(frontendRoot, 'src', 'routes', 'v1', 'AdminRoutes.tsx'),
];

const args = process.argv.slice(2);
const check = args.includes('--check');
const writeManifest = args.includes('--write-manifest');
const outputFlag = args.indexOf('--nginx-output');
const nginxOutput =
    outputFlag === -1 ? null : path.resolve(frontendRoot, args[outputFlag + 1]);

if (outputFlag !== -1 && !args[outputFlag + 1]) {
    throw new Error('--nginx-output requires a path');
}

function extractRoutes() {
    const routes = new Set();

    for (const sourcePath of routeSources) {
        const source = ts.createSourceFile(
            sourcePath,
            fs.readFileSync(sourcePath, 'utf8'),
            ts.ScriptTarget.Latest,
            true,
            ts.ScriptKind.TSX,
        );

        function visit(node) {
            if (ts.isJsxAttribute(node) && node.name.getText(source) === 'path') {
                if (!node.initializer || !ts.isStringLiteral(node.initializer)) {
                    throw new Error(
                        `${sourcePath}: Route path attributes must be string literals so edge parity can be verified`,
                    );
                }
                const route = node.initializer.text;
                if (route !== '*' && !route.startsWith('/test/')) {
                    if (!route.startsWith('/')) {
                        throw new Error(`${sourcePath}: route must start with /: ${route}`);
                    }
                    routes.add(route);
                }
            }
            ts.forEachChild(node, visit);
        }

        visit(source);
    }

    return [...routes].sort();
}

function readManifest() {
    const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
    if (manifest.schema_version !== 1 || !Array.isArray(manifest.routes)) {
        throw new Error('edge-route-manifest.json must use schema_version 1 and a routes array');
    }
    if (new Set(manifest.routes).size !== manifest.routes.length) {
        throw new Error('edge-route-manifest.json contains duplicate routes');
    }
    if (JSON.stringify(manifest.routes) !== JSON.stringify([...manifest.routes].sort())) {
        throw new Error('edge-route-manifest.json routes must remain sorted');
    }
    return manifest;
}

function diffRoutes(expected, actual) {
    const expectedSet = new Set(expected);
    const actualSet = new Set(actual);
    return {
        missing: expected.filter(route => !actualSet.has(route)),
        stale: actual.filter(route => !expectedSet.has(route)),
    };
}

function escapeRegex(value) {
    return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function routeRegex(route) {
    if (route === '/') return '^/$';
    const segments = route
        .split('/')
        .filter(Boolean)
        .map(segment => {
            if (segment.startsWith(':')) {
                if (!/^:[A-Za-z][A-Za-z0-9_]*$/.test(segment)) {
                    throw new Error(`Unsupported dynamic route segment: ${segment}`);
                }
                return '[^/]+';
            }
            if (segment.includes('*')) {
                throw new Error(`Unsupported wildcard route segment: ${segment}`);
            }
            return escapeRegex(segment);
        });
    return `^/${segments.join('/')}/?$`;
}

function renderNginx(routes) {
    const entries = routes.map(route => `    ~${routeRegex(route)} 1;`).join('\n');
    return `# Generated by scripts/generate-edge-routes.mjs. Do not edit.\n` +
        `map $uri $clpr_spa_route {\n` +
        `    default 0;\n${entries}\n}\n`;
}

const extractedRoutes = extractRoutes();

if (writeManifest) {
    fs.writeFileSync(
        manifestPath,
        `${JSON.stringify({ schema_version: 1, routes: extractedRoutes }, null, 2)}\n`,
    );
}

const manifest = readManifest();
const difference = diffRoutes(extractedRoutes, manifest.routes);
if (difference.missing.length || difference.stale.length) {
    if (difference.missing.length) {
        console.error(`Routes missing from edge manifest: ${difference.missing.join(', ')}`);
    }
    if (difference.stale.length) {
        console.error(`Stale routes in edge manifest: ${difference.stale.join(', ')}`);
    }
    process.exit(1);
}

if (nginxOutput) {
    fs.writeFileSync(nginxOutput, renderNginx(manifest.routes));
}

if (check) {
    console.log(`edge routes: ${manifest.routes.length} production routes match React`);
}
